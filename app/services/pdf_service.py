# SAFE VALUE HELPERS
# =====================================================

def safe_text(value, default="Not available."):

    if value is None:
        return default

    if isinstance(value, str):

        value = value.strip()

        if not value:
            return default

        return value

    if isinstance(value, list):

        if not value:
            return default

        return ", ".join(
            str(item)
            for item in value
        )

    if isinstance(value, dict):

        if not value:
            return default

        return " | ".join(
            f"{key}: {val}"
            for key, val in value.items()
        )

    return str(value)


def safe_list(value):

    if value is None:
        return []

    if isinstance(value, list):
        return value

    if isinstance(value, tuple):
        return list(value)

    if isinstance(value, str):

        if not value.strip():
            return []

        return [value]

    return [value]


def escape_html(text):

    text = safe_text(
        text,
        ""
    )

    return (
        text
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
        .replace("'", "&#39;")
    )


