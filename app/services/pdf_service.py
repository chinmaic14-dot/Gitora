# REBUILD OPTIONS
# =====================================================

def build_rebuild_options(
    options,
    styles
):

    elements = []

    options = safe_list(options)

    if not options:

        elements.append(
            Paragraph(
                "No rebuild approaches were generated.",
                styles["BodyTextCustom"]
            )
        )

        return elements

    for index, option in enumerate(
        options[:3],
        start=1
    ):

        if isinstance(option, dict):

            title = (
                option.get("title")
                or option.get("name")
                or option.get("approach")
                or f"Approach {index}"
            )

            description = (
                option.get("description")
                or option.get("details")
                or option.get("method")
                or option.get("technology")
                or ""
            )

            content = (
                str(title)
                + "\n\n"
                + str(description)
            )

        else:

            content = str(option)

        elements.append(
            create_analysis_box(
                f"Approach {index}",
                content,
                styles
            )
        )

        elements.append(
            Spacer(1, 8)
        )

    return elements


