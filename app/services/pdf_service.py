# =====================================================
# BULLET LIST
# =====================================================

def bullet_list(items, styles):

    elements = []

    items = safe_list(items)

    if not items:

        elements.append(
            Paragraph(
                "None identified.",
                styles["BodyTextCustom"]
            )
        )

        return elements

    for item in items:

        if isinstance(item, dict):

            text = " | ".join(
                f"{key}: {value}"
                for key, value in item.items()
            )

        else:

            text = str(item)

        elements.append(
            Paragraph(
                "• " + escape_html(text),
                styles["BulletCustom"]
            )
        )

    return elements


